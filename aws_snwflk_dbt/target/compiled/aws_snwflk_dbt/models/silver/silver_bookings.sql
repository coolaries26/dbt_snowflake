

SELECT
    BOOKING_ID,
    LISTING_ID,
    BOOKING_DATE,
    NIGHTS_BOOKED,
    
    ROUND(BOOKING_AMOUNT / NIGHTS_BOOKED, 2)
 AS PER_NIGHT_CHARGES,
    CLEANING_FEE,
    SERVICE_FEE,
    BOOKING_STATUS,
    BOOKING_AMOUNT,
    CREATED_AT
FROM abnb.bronze.bronze_bookings
WHERE BOOKING_STATUS <> 'CANCELLED'


    AND CREATED_AT >= (
        SELECT COALESCE(
            MAX(CREATED_AT),
            '1900-01-01'::TIMESTAMP_NTZ
        )
        FROM abnb.silver.silver_bookings
    )
